-- V1: the database schema. Flyway runs files named V<number>__<description>.sql once, in order.
-- NEVER edit a migration after it has run on a real database; add V3, V4, ... instead.
-- The SQL below is standard, so it runs on both PostgreSQL and H2.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    email         VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,              -- BCrypt hash, never the real password
    role          VARCHAR(20)  NOT NULL,              -- ADMIN or STAFF
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           VARCHAR(40)   NOT NULL UNIQUE,      -- SKU = Stock Keeping Unit, the shop's own product code
    name          VARCHAR(120)  NOT NULL,
    description   VARCHAR(500),
    price         NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    quantity      INTEGER       NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reorder_level INTEGER       NOT NULL DEFAULT 5 CHECK (reorder_level >= 0),
    category_id   BIGINT        NOT NULL REFERENCES categories (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Every change of stock is a row here: an audit trail you can replay.
CREATE TABLE stock_movements (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT      NOT NULL REFERENCES products (id),
    movement_type      VARCHAR(10) NOT NULL,          -- IN or OUT
    quantity           INTEGER     NOT NULL CHECK (quantity > 0),
    note               VARCHAR(255),
    created_by         VARCHAR(50) NOT NULL,          -- username of the person who made the change
    resulting_quantity INTEGER     NOT NULL CHECK (resulting_quantity >= 0),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes make lookups by these columns fast.
CREATE INDEX idx_products_category    ON products (category_id);
CREATE INDEX idx_movements_product    ON stock_movements (product_id, created_at);
